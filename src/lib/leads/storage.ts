import { randomBytes } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/** Private folder for customer uploads (never served publicly; admin-only download route). */
export const UPLOAD_DIR = process.env.UPLOAD_DIR ?? path.join(process.cwd(), "storage", "uploads");

export const MAX_FILES = 5;
export const MAX_FILE_BYTES = 10 * 1024 * 1024;
export const ALLOWED_EXT = ["pdf", "ai", "eps", "png", "jpg", "jpeg", "svg", "zip"];

export type StoredFile = { name: string; storedName: string; size: number; type: string };

const MIME: Record<string, string> = {
  pdf: "application/pdf",
  ai: "application/postscript",
  eps: "application/postscript",
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  svg: "image/svg+xml",
  zip: "application/zip",
};

export function extOf(name: string) {
  return name.split(".").pop()?.toLowerCase() ?? "";
}

export function mimeFor(name: string) {
  return MIME[extOf(name)] ?? "application/octet-stream";
}

/** Returns an error message, or null when the file is acceptable. */
export function validateUpload(file: File): string | null {
  if (!ALLOWED_EXT.includes(extOf(file.name))) return `"${file.name}" is not a supported file type.`;
  if (file.size === 0) return `"${file.name}" is empty.`;
  if (file.size > MAX_FILE_BYTES) return `"${file.name}" is over 10 MB.`;
  return null;
}

export async function saveUpload(file: File): Promise<StoredFile> {
  await mkdir(UPLOAD_DIR, { recursive: true });
  const ext = extOf(file.name);
  const base = file.name
    .replace(/\.[^.]+$/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  const storedName = `${Date.now()}-${randomBytes(6).toString("hex")}-${base || "file"}.${ext}`;
  await writeFile(path.join(UPLOAD_DIR, storedName), Buffer.from(await file.arrayBuffer()));
  return { name: file.name.slice(0, 160), storedName, size: file.size, type: mimeFor(file.name) };
}

export async function readUpload(storedName: string) {
  // storedName is generated by us; still refuse anything that is not a plain file name.
  if (!/^[a-z0-9._-]+$/.test(storedName) || storedName.includes("..")) return null;
  try {
    return await readFile(path.join(UPLOAD_DIR, storedName));
  } catch {
    return null;
  }
}
